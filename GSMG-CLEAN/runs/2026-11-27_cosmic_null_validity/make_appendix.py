#!/usr/bin/env python3
"""Render APPENDIX_GAP_STRINGS.md from the two gap-set artifacts.

Reads gapset_v2/gap_candidates.txt and gapset_v2/gap_provenance.tsv and writes the
appendix that REPORT.md cites. Nothing is recomputed and nothing is added: the
appendix is a view of the committed artifacts, so it can be regenerated byte for
byte by re-running this script.

  python runs/2026-11-27_cosmic_null_validity/make_appendix.py
"""
import hashlib
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAP = HERE / 'gapset_v2'
OUT = HERE / 'APPENDIX_GAP_STRINGS.md'
SHOW_S60 = 40


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load():
    rows = []
    lines = (GAP / 'gap_provenance.tsv').read_text(encoding='utf-8').split('\n')
    assert lines[0] == 'candidate\tsources'
    for line in lines[1:]:
        if not line:
            continue
        text, _, sources = line.rpartition('\t')
        rows.append((text, sources.split(' | ')))
    return rows


def family_of(source):
    if 'unity_of_opposites_audit.json' in source:
        return '1. unity of opposites (10)'
    if '5g-puzzle packet' in source:
        return '2. 5g-puzzle frozen packet list (199)'
    if 'v50 _creator_texts' in source:
        return '3. v50-A named creator texts (35)'
    if 'CHECKPOINT_4F7A_VS_A5502' in source:
        return '4. checkpoint master key (1)'
    return '5. SalPhaseIon pre-registration v1-v22, text preimages (3,263)'


def main():
    rows = load()
    groups = OrderedDict()
    for text, sources in rows:
        for fam in dict.fromkeys(family_of(s) for s in sources):
            groups.setdefault(fam, []).append((text, sources))

    out = ['# Appendix — exact gap strings and provenance', '',
           'Generated by `make_appendix.py` from `gapset_v2/gap_candidates.txt` '
           '(sha256 `%s`) and' % sha(GAP / 'gap_candidates.txt'),
           '`gapset_v2/gap_provenance.tsv` (sha256 `%s`).' % sha(GAP / 'gap_provenance.tsv'),
           'Unique candidates in the set: %d. Rows below: %d (a string that belongs to two'
           % (len(rows), sum(len(v) for v in groups.values())),
           'families is listed under each).', '']

    for key, items in sorted(groups.items()):
        out.append('## ' + key)
        out.append('')
        if key.startswith('5.'):
            prov = Counter(src.split(' / ', 1)[1] if ' / ' in src else src
                           for _, srcs in items for src in srcs if 'SALPHASEION' in src)
            out.append('Distinct provenance strings: %d. First %d shown; the whole map is in '
                       '`gap_provenance.tsv`.' % (len(prov), SHOW_S60))
            out.append('')
            for text, sources in items[:SHOW_S60]:
                provs = [s.split(' / ', 1)[-1] for s in sources if 'SALPHASEION' in s]
                out.append('- `%r` — %s' % (text, provs[0] if provs else sources[0]))
            out.append('')
            out.append('Provenance families by count:')
            out.append('')
            for name, count in prov.most_common():
                out.append('- %d × `%s`' % (count, name))
        else:
            for index, (text, sources) in enumerate(items, 1):
                out.append('%3d. `%s` — %s' % (index, text, '; '.join(sources)))
        out.append('')

    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('wrote %s (%d bytes, %d unique rows, %d listed)'
          % (OUT, OUT.stat().st_size, len(rows), sum(len(v) for v in groups.values())))
    print('sha256', sha(OUT))


if __name__ == '__main__':
    main()
